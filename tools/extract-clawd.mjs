// Regenerates hooks/clawd-sprites.ts from the Claude desktop app's bundled Clawd sprite data.
// Run with: node tools/extract-clawd.mjs [/Applications/Claude.app]
import fs from 'node:fs'
import path from 'node:path'

const app = process.argv[2] ?? '/Applications/Claude.app'
const asarPath = path.join(app, 'Contents/Resources/app.asar')
const out = new URL('../hooks/clawd-sprites.ts', import.meta.url)

// Each activity plays one of the clips the app itself defines (clawdQuestEngine's clip table).
const CLIPS = {
  idle: { sprite: 'Swaying', from: 4, to: 48 },
  thinking: { sprite: 'Thinking', from: 2, to: 36 },
  building: { sprite: 'Laptop', from: 17, to: 33 },
  running: { sprite: 'Desktop', from: 15, to: 75 },
  exploring: { sprite: 'LookingAround', from: 4, to: 30 },
  done: { sprite: 'DancingHappy', from: 6, to: 38 },
  greeting: { sprite: 'Waving', from: 3, to: 16 },
  planning: { sprite: 'Lightbulb', from: 2, to: 48 },
  oops: { sprite: 'Facepalm', from: 2, to: 33 },
  disappointed: { sprite: 'Disappointed', from: 2, to: 42 },
  party: { sprite: 'Hula', from: 0, to: 53 },
  resting: { sprite: 'Meditating', from: 2, to: 59 },
  dizzy: { sprite: 'Dizzy', from: 0, to: 40 },
}
const FPS = 12
// The window every clip is drawn into, in sprite pixels; the body (24x16) sits on its bottom edge.
const WINDOW_W = 36
const WINDOW_H = 26

const readAsarFile = (want) => {
  const fd = fs.openSync(asarPath, 'r')
  const head = Buffer.alloc(16)
  fs.readSync(fd, head, 0, 16, 0)
  const headerSize = head.readUInt32LE(4)
  const jsonLen = head.readUInt32LE(12)
  const json = Buffer.alloc(jsonLen)
  fs.readSync(fd, json, 0, jsonLen, 16)
  const walk = (node, prefix) =>
    Object.entries(node.files ?? {}).flatMap(([k, v]) => (v.files ? walk(v, `${prefix}/${k}`) : [[`${prefix}/${k}`, v]]))
  const entry = walk(JSON.parse(json.toString()), '').find(([p]) => want.test(p))
  if (!entry) throw new Error(`no file matching ${want} in ${asarPath}`)
  const buf = Buffer.alloc(entry[1].size)
  fs.readSync(fd, buf, 0, entry[1].size, 8 + headerSize + Number(entry[1].offset))
  return buf.toString('utf8')
}

const engine = readAsarFile(/clawdQuestEngine-[^/]+\.js$/)
const start = engine.indexOf('{BreakDancing:')
const end = engine.indexOf(';function ', start)
const sprites = (0, eval)(`(${engine.slice(start, end)})`)

const decode = (t) => {
  const frames = []
  const r = Uint8Array.from([...t.base].map((c) => (c === '.' ? 255 : parseInt(c, 36))))
  frames.push(r.slice())
  for (const d of t.deltas) {
    if (d) for (const tok of d.split(',')) r[parseInt(tok.slice(0, -1), 36)] = tok.at(-1) === '.' ? 255 : parseInt(tok.at(-1), 36)
    frames.push(r.slice())
  }
  return frames
}

const framePaths = (t, f, dx, dy) => {
  const runs = {}
  for (let y = 0; y < t.h; y++) {
    for (let x = 0; x < t.w; ) {
      const c = f[y * t.w + x]
      if (c === 255) { x++; continue }
      let x2 = x
      while (x2 + 1 < t.w && f[y * t.w + x2 + 1] === c) x2++
      const wx = x + dx, wy = y + dy, len = x2 - x + 1
      if (wy >= 0) (runs[c] ??= []).push(`M${wx} ${wy}h${len}v1h-${len}z`)
      x = x2 + 1
    }
  }
  return Object.entries(runs).map(([c, d]) => `<path fill="${t.palette[c]}" d="${d.join('')}"/>`).join('')
}

const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v))

const result = {}
for (const [activity, clip] of Object.entries(CLIPS)) {
  const t = sprites[clip.sprite]
  const [ax, ay, aw, ah] = t.a0[2] > 0 ? t.a0 : [0, 0, t.w, t.h]
  // Centre the body, but slide a wide sprite (a desk, a laptop) back inside the window rather than crop it.
  const dx = clamp(Math.round(WINDOW_W / 2 - (ax + aw / 2)), Math.min(0, WINDOW_W - t.w), Math.max(0, WINDOW_W - t.w))
  const frames = decode(t).slice(clip.from, clip.to + 1)
  const top = Math.min(...frames.map((f) => Math.floor(f.findIndex((c) => c !== 255) / t.w)))
  // A clip taller than the window (a lightbulb, a thought bubble) shrinks to fit instead of losing its top.
  const scale = Math.min(1, WINDOW_H / (ay + ah - top))
  const dy = WINDOW_H / scale - (ay + ah)
  const n = frames.length
  const dur = (n / FPS).toFixed(3)
  result[activity] = frames
    .map((f, i) => {
      const k = `0;${(i / n).toFixed(4)};${((i + 1) / n).toFixed(4)}`
      return `<g visibility="hidden"><animate attributeName="visibility" values="hidden;visible;hidden" keyTimes="${k}" dur="${dur}s" calcMode="discrete" repeatCount="indefinite"/>${framePaths(t, f, dx, dy)}</g>`
    })
    .join('')
  if (scale < 1) {
    const shiftX = ((WINDOW_W - WINDOW_W * scale) / 2).toFixed(2)
    result[activity] = `<g transform="translate(${shiftX} 0) scale(${scale.toFixed(4)})">${result[activity]}</g>`
  }
}

const body = Object.entries(result).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')
fs.writeFileSync(
  out,
  `// Generated by tools/extract-clawd.mjs from the Claude desktop app's Clawd sprites; regenerate, never hand-edit.\n` +
    `import type { Activity } from '../types'\n\n` +
    `export const CLAWD_WINDOW = { width: ${WINDOW_W}, height: ${WINDOW_H} } as const\n\n` +
    `export const CLAWD_FRAMES: Record<Activity, string> = {\n${body}\n}\n`,
)
console.log('wrote', out.pathname, Object.fromEntries(Object.entries(result).map(([k, v]) => [k, `${(v.length / 1024).toFixed(0)}KB`])))
